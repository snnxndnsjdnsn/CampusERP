/** Collapse a multi line SQL fragment into a single line. */
function oneLine(text) {
  return String(text ?? '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Render a value that may be missing as a dash. */
function dash(value) {
  return value === null || value === undefined || value === '' ? '-' : `\`${value}\``;
}

/** The identity column of a column, in words. */
function identityText(column) {
  if (column.identity === 'a') return 'GENERATED ALWAYS AS IDENTITY';
  if (column.identity === 'd') return 'GENERATED BY DEFAULT AS IDENTITY';
  if (column.generated === 's') return 'GENERATED ALWAYS AS (...) STORED';
  if (column.generated) return `GENERATED ALWAYS AS (${column.generated})`;
  return '-';
}

/** The label of a constraint, in words. */
const CONSTRAINT_LABELS = {
  p: 'Primary key',
  u: 'Unique',
  c: 'Check',
  f: 'Foreign key',
  x: 'Exclusion',
  t: 'Trigger',
};

/** The objects of one schema. */
function inSchema(rows, schema) {
  return rows.filter((row) => row.schema === schema);
}

/** Render the whole document. */
export function render(catalogue) {
  const lines = [];
  const counts = catalogue.counts;

  lines.push('# Database schema');
  lines.push('');
  lines.push(
    '<!-- GENERATED FILE - do not edit by hand. Regenerate with ' +
      '`node tools/validate/schema_doc.mjs` (or `npm run docs:schema`). -->',
  );
  lines.push('');
  lines.push(
    `Source of truth: the live Supabase project \`${PROJECT}\` ` +
      `(PostgreSQL ${catalogue.server_version}), read with \`SELECT\` only. ` +
      'The catalogue behind this document is `tools/catalogue/live_catalogue.json`.',
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push('| Object | Count |');
  lines.push('|---|---|');
  lines.push(`| Schemas | ${catalogue.schemas.length} |`);
  lines.push(`| Tables | ${counts.tables} |`);
  lines.push(`| Tables with row level security | ${counts.rls_tables} |`);
  lines.push(`| Views | ${counts.views} |`);
  lines.push(`| Functions | ${counts.functions} |`);
  lines.push(`| Triggers | ${counts.triggers} |`);
  lines.push(`| Policies | ${counts.policies} |`);
  lines.push(`| Indexes | ${counts.indexes} |`);
  lines.push(`| Sequences | ${counts.sequences} |`);
  lines.push(`| Domains | ${counts.domains} |`);
  lines.push(`| Enums | ${counts.enums} |`);
  lines.push(`| Composite types | ${counts.composites} |`);
  lines.push(`| Grants | ${counts.grants} |`);
  lines.push('');

  for (const schema of catalogue.schemas) {
    const tables = inSchema(catalogue.tables, schema);
    const views = inSchema(catalogue.views, schema);
    const functions = inSchema(catalogue.functions, schema);
    const triggers = inSchema(catalogue.triggers, schema);
    const policies = inSchema(catalogue.policies, schema);
    const indexes = inSchema(catalogue.indexes, schema);

    lines.push(`## Schema \`${schema}\``);
    lines.push('');
    lines.push(
      `${tables.length} tables, ${views.length} views, ${functions.length} functions, ` +
        `${triggers.length} triggers, ${policies.length} policies, ${indexes.length} indexes.`,
    );
    lines.push('');

    // --- tables -------------------------------------------------------------
    lines.push(`### Tables (${tables.length})`);
    lines.push('');
    for (const table of tables) {
      const tableIndexes = indexes.filter((index) => index.table === table.name);
      lines.push(`#### \`${schema}.${table.name}\``);
      lines.push('');
      lines.push(
        `Row level security: **${table.rls ? 'enabled' : 'disabled'}**. ` +
          `Columns: **${table.columns.length}**. Indexes: **${tableIndexes.length}**.`,
      );
      lines.push('');
      lines.push('| Column | Type | Nullable | Default | Identity / generated |');
      lines.push('|---|---|---|---|---|');
      for (const column of table.columns) {
        lines.push(
          `| \`${column.name}\` | \`${column.type}\` | ${column.not_null ? 'no' : 'yes'} | ` +
            `${dash(column.default)} | ${identityText(column)} |`,
        );
      }
      lines.push('');
      for (const type of ['p', 'u', 'c', 'f', 'x', 't']) {
        for (const constraint of table.constraints.filter((c) => c.type === type)) {
          lines.push(
            `- **${CONSTRAINT_LABELS[type]}** \`${constraint.name}\`: ${constraint.definition}`,
          );
        }
      }
      for (const index of tableIndexes) {
        lines.push(`- **Index** \`${index.name}\`: ${index.definition}`);
      }
      lines.push('');
    }

    // --- views --------------------------------------------------------------
    lines.push(`### Views (${views.length})`);
    lines.push('');
    if (views.length) {
      lines.push('| View | Kind | Definition |');
      lines.push('|---|---|---|');
      for (const view of views) {
        lines.push(`| \`${view.name}\` | ${view.kind} | \`${oneLine(view.body)}\` |`);
      }
    } else {
      lines.push('_none_');
    }
    lines.push('');

    // --- functions ----------------------------------------------------------
    lines.push(`### Functions (${functions.length})`);
    lines.push('');
    if (functions.length) {
      lines.push('| Function | Arguments |');
      lines.push('|---|---|');
      for (const fn of functions) {
        lines.push(`| \`${schema}.${fn.name}\` | ${dash(fn.args)} |`);
      }
    } else {
      lines.push('_none_');
    }
    lines.push('');

    // --- triggers -----------------------------------------------------------
    lines.push(`### Triggers (${triggers.length})`);
    lines.push('');
    if (triggers.length) {
      lines.push('| Trigger | Table | Definition |');
      lines.push('|---|---|---|');
      for (const trigger of triggers) {
        lines.push(
          `| \`${trigger.name}\` | \`${trigger.table}\` | \`${oneLine(trigger.definition)}\` |`,
        );
      }
    } else {
      lines.push('_none_');
    }
    lines.push('');

    // --- policies -----------------------------------------------------------
    lines.push(`### Policies (${policies.length})`);
    lines.push('');
    if (policies.length) {
      lines.push('| Table | Policy | Command | Roles |');
      lines.push('|---|---|---|---|');
      for (const policy of policies) {
        lines.push(
          `| \`${policy.table}\` | \`${policy.name}\` | ${policy.command} | ` +
            `${(policy.roles || []).join(', ')} |`,
        );
      }
    } else {
      lines.push('_none_');
    }
    lines.push('');
  }

  // --- domains -------------------------------------------------------------
  lines.push('## Domains');
  lines.push('');
  if (catalogue.domains.length) {
    lines.push('| Domain | Base type | Check |');
    lines.push('|---|---|---|');
    for (const domain of catalogue.domains) {
      lines.push(`| \`${domain.name}\` | \`${domain.base_type}\` | ${dash(domain.check)} |`);
    }
  } else {
    lines.push('_none_');
  }
  lines.push('');

  // --- sequences -----------------------------------------------------------
  lines.push('## Sequences');
  lines.push('');
  if (catalogue.sequences.length) {
    lines.push('| Sequence | Type | Owned by |');
    lines.push('|---|---|---|');
    for (const sequence of catalogue.sequences) {
      lines.push(`| \`${sequence.name}\` | \`${sequence.type}\` | ${dash(sequence.owned_by)} |`);
    }
  } else {
    lines.push('_none_');
  }
  lines.push('');

  return lines.join('\n');
}

/* ------------------------------------------------------------------------- *
 * the reconciliation of the MySQL source with the PostgreSQL schema
 * ------------------------------------------------------------------------- */

/** The two spellings of the timestamp type. */
const TYPE_ALIASES = new Map([['timestamptz', 'timestamp with time zone']]);

/** Do the two type names describe the same PostgreSQL type? */
function sameType(mysqlType, pgType) {
  if (mysqlType === pgType) return true;
  return (TYPE_ALIASES.get(mysqlType) ?? mysqlType) === (TYPE_ALIASES.get(pgType) ?? pgType);
}

/**
 * Normalise a column default so that the two spellings compare equal.
 *
 * PostgreSQL prints the cast of a literal (`'OTHER'::text`) and writes the
 * booleans in lower case; MySQL writes neither.
 */
function normaliseDefault(value) {
  if (value === null || value === undefined) return null;
  let text = String(value).trim();
  text = text.replace(/'((?:[^']|'')*)'::[a-z_ ]+/g, "'$1'");
  text = text.replace(/\bTRUE\b/g, 'true').replace(/\bFALSE\b/g, 'false');
  text = text.replace(/\s+/g, ' ');
  return text;
}

/** The columns of a `PRIMARY KEY (a, b)` definition. */
function constraintColumns(definition) {
  const match = /\(([^)]*)\)/.exec(String(definition ?? ''));
  if (!match) return [];
  return match[1]
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean);
}

/** Compare the MySQL source with the PostgreSQL schema. */
export function reconcile(catalogue, reference) {
  const pgTables = new Map(
    catalogue.tables.filter((table) => table.schema === 'public').map((table) => [table.name, table]),
  );
  const mysqlTables = reference.tables;

  const counts = {
    mysql: {
      tables: mysqlTables.length,
      columns: 0,
      pk: 0,
      fk: 0,
      uq: 0,
      check: 0,
      index: reference.indexes.length,
    },
    pg: {
      tables: pgTables.size,
      columns: 0,
      pk: 0,
      fk: 0,
      uq: 0,
      check: 0,
      index: catalogue.indexes.filter((index) => index.schema === 'public').length,
    },
  };

  const differences = new Map();
  const defects = [];

  const add = (table, entry) => {
    if (!differences.has(table)) differences.set(table, []);
    differences.get(table).push(entry);
  };

  for (const table of pgTables.values()) {
    counts.pg.columns += table.columns.length;
    for (const constraint of table.constraints) {
      if (constraint.type === 'p') counts.pg.pk += 1;
      else if (constraint.type === 'f') counts.pg.fk += 1;
      else if (constraint.type === 'u') counts.pg.uq += 1;
      else if (constraint.type === 'c' && !constraint.name.startsWith('enum_')) counts.pg.check += 1;
    }
  }

  for (const table of mysqlTables) {
    counts.mysql.columns += table.columns.length;
    if (table.primary_key.length) counts.mysql.pk += 1;
    counts.mysql.fk += table.foreign_keys.length;
    counts.mysql.uq += table.unique_constraints.length;
    counts.mysql.check += table.checks.length;

    const pg = pgTables.get(table.name);
    if (!pg) {
      add(table.name, {
        kind: 'missing table',
        column: '-',
        mysql: `${table.columns.length} columns`,
        postgres: null,
      });
      continue;
    }

    const pgColumns = new Map(pg.columns.map((column) => [column.name, column]));

    for (const duplicate of table.duplicate_columns || []) {
      defects.push({
        id: 'SD-1',
        table: table.name,
        column: duplicate,
        finding:
          'the source defines the column twice (the CREATE TABLE and the ALTER ' +
          'TABLE ... ADD COLUMN); MySQL aborts with "Duplicate column name", the ' +
          'migration set adds the column only once',
      });
    }

    for (const column of table.columns) {
      const pgColumn = pgColumns.get(column.name);
      if (!pgColumn) {
        add(table.name, {
          kind: 'missing column',
          column: column.name,
          mysql: column.type,
          postgres: null,
        });
        continue;
      }
      if (column.auto_increment) {
        // the width of an identity column is a deliberate divergence
        if (!pgColumn.identity) {
          add(table.name, {
            kind: 'missing identity column',
            column: column.name,
            mysql: 'AUTO_INCREMENT',
            postgres: pgColumn.type,
          });
        }
      } else if (!sameType(column.type, pgColumn.type)) {
        add(table.name, {
          kind: 'different type',
          column: column.name,
          mysql: column.type,
          postgres: pgColumn.type,
        });
      }
      if (column.nullable === pgColumn.not_null) {
        add(table.name, {
          kind: 'different nullability',
          column: column.name,
          mysql: column.nullable ? 'NULL' : 'NOT NULL',
          postgres: pgColumn.not_null ? 'NOT NULL' : 'NULL',
        });
      }
      if (!pgColumn.generated) {
        const mysqlDefault = normaliseDefault(column.default);
        const pgDefault = normaliseDefault(pgColumn.default);
        if (mysqlDefault !== pgDefault) {
          add(table.name, {
            kind: 'different default',
            column: column.name,
            mysql: mysqlDefault,
            postgres: pgDefault,
          });
        }
      }
    }

    // --- constraints --------------------------------------------------------
    const expected = { fk: new Set(), uq: new Set(), check: new Set() };
    for (const fk of table.foreign_keys) {
      expected.fk.add(fk.name || `${table.name}_${fk.columns.join('_')}_fkey`);
    }
    for (const uq of table.unique_constraints) {
      expected.uq.add(uq.name || `${table.name}_${uq.columns.join('_')}_key`);
    }
    for (const check of table.checks) {
      expected.check.add(check.name || `${table.name}_check`);
    }

    const pgConstraints = new Map(pg.constraints.map((constraint) => [constraint.name, constraint]));

    if (table.primary_key.length) {
      const primary = pg.constraints.find((constraint) => constraint.type === 'p');
      if (!primary) {
        add(table.name, {
          kind: 'missing primary key',
          column: '-',
          mysql: `PRIMARY KEY (${table.primary_key.join(', ')})`,
          postgres: null,
        });
      } else {
        const columns = constraintColumns(primary.definition);
        if (columns.join(',') !== table.primary_key.join(',')) {
          add(table.name, {
            kind: 'different primary key',
            column: '-',
            mysql: `PRIMARY KEY (${table.primary_key.join(', ')})`,
            postgres: primary.definition,
          });
        }
      }
    }

    for (const [kind, names] of Object.entries(expected)) {
      for (const name of names) {
        if (!pgConstraints.has(name)) {
          add(table.name, {
            kind: `missing ${kind === 'fk' ? 'foreign key' : kind === 'uq' ? 'unique constraint' : 'check constraint'}`,
            column: name,
            mysql: name,
            postgres: null,
          });
        }
      }
    }

    for (const constraint of pg.constraints) {
      if (constraint.type === 'f' && !expected.fk.has(constraint.name)) {
        add(table.name, {
          kind: 'extra foreign key',
          column: constraint.name,
          mysql: null,
          postgres: constraint.definition,
        });
      } else if (constraint.type === 'u' && !expected.uq.has(constraint.name)) {
        add(table.name, {
          kind: 'extra unique constraint',
          column: constraint.name,
          mysql: null,
          postgres: constraint.definition,
        });
      } else if (
        constraint.type === 'c' &&
        !constraint.name.startsWith('enum_') &&
        !expected.check.has(constraint.name)
      ) {
        add(table.name, {
          kind: 'extra check constraint',
          column: constraint.name,
          mysql: null,
          postgres: constraint.definition,
        });
      }
    }
  }

  // the tables PostgreSQL has that the MySQL source does not know
  const mysqlNames = new Set(mysqlTables.map((table) => table.name));
  for (const name of pgTables.keys()) {
    if (!mysqlNames.has(name)) {
      add(name, {
        kind: 'extra table',
        column: '-',
        mysql: null,
        postgres: `${pgTables.get(name).columns.length} columns`,
      });
    }
  }

  const differing = differences.size;
  return {
    counts,
    differences,
    defects,
    identicalTables: mysqlTables.length - differing,
  };
}

/** The divergences between MySQL and PostgreSQL that are deliberate. */
const DIVERGENCES = [
  ['`AUTO_INCREMENT`', '`GENERATED BY DEFAULT AS IDENTITY`', 'the sequence is resynced in 015'],
  [
    '`TINYINT/SMALLINT/INT/BIGINT UNSIGNED`',
    'domains `u8`/`u16`/`u32`/`u64`',
    'the range is checked by the domain; the identity columns use the plain integer type',
  ],
  ['`ENUM(...)`', '`text` + named `CHECK (col IN (...))`', 'the check keeps the value list'],
  ['`BOOLEAN`', '`boolean`', '-'],
  ['`TIMESTAMP`, `DATETIME`', '`timestamptz`', 'the source assumes a UTC session'],
  ['`YEAR`', 'domain `u_year`', '1901-2155'],
  ['`JSON`', '`jsonb`', 'the key order is not preserved'],
  ['`VARBINARY`', '`bytea`', '-'],
  [
    '`ON UPDATE CURRENT_TIMESTAMP`',
    '`BEFORE UPDATE` trigger `sims_touch_updated_at()`',
    'the trigger only bumps the column when the row really changed',
  ],
  ['`INSERT IGNORE`', '`ON CONFLICT DO NOTHING`', '-'],
  ['`REGEXP`', '`~`', '-'],
  [
    '`DATEDIFF`, `TIMESTAMPDIFF`, `IFNULL`, `DATE()`',
    '`date - date`, `age()`, `COALESCE`, `CAST(.. AS date)`',
    '-',
  ],
  [
    "`SIGNAL SQLSTATE '45000'`, `<=>`",
    "`RAISE EXCEPTION .. ERRCODE '45000'`, `IS NOT DISTINCT FROM`",
    'the triggers are ported to PL/pgSQL',
  ],
];

/** Render the reconciliation document. */
export function renderReconciliation(catalogue, reference) {
  const result = reconcile(catalogue, reference);
  const { counts } = result;
  const lines = [];

  const same = (a, b) => (a === b ? 'same number' : 'different number');

  lines.push('# Schema reconciliation');
  lines.push('');
  lines.push(
    'Generated by `node tools/validate/schema_doc.mjs` from ' +
      `\`${reference.source}\` and the migration set. Do not edit by hand.`,
  );
  lines.push('');
  lines.push(
    'The MySQL source is the functional specification, the PostgreSQL schema is what ' +
      '`supabase/migrations/` builds. Every table, column, type, nullability flag, ' +
      'default and named constraint of the source is looked up in the rebuilt ' +
      'database; the MySQL types are translated with the rules of ' +
      '`docs/DATABASE_MIGRATION.md` before the comparison, so only a real divergence ' +
      'is reported.',
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push('| Object | MySQL source | PostgreSQL | Result |');
  lines.push('|---|---|---|---|');
  lines.push(`| Tables | ${counts.mysql.tables} | ${counts.pg.tables} | identical names |`);
  lines.push(`| Columns | ${counts.mysql.columns} | ${counts.pg.columns} | ${same(counts.mysql.columns, counts.pg.columns)} |`);
  lines.push(`| Primary keys | ${counts.mysql.pk} | ${counts.pg.pk} | ${same(counts.mysql.pk, counts.pg.pk)} |`);
  lines.push(`| Foreign keys | ${counts.mysql.fk} | ${counts.pg.fk} | ${same(counts.mysql.fk, counts.pg.fk)} |`);
  lines.push(`| Unique constraints | ${counts.mysql.uq} | ${counts.pg.uq} | ${same(counts.mysql.uq, counts.pg.uq)} |`);
  lines.push(`| Check constraints | ${counts.mysql.check} | ${counts.pg.check} | ${same(counts.mysql.check, counts.pg.check)} |`);
  lines.push(
    `| Declared indexes | ${counts.mysql.index} | ${counts.pg.index} | ` +
      'the source declares standalone `CREATE INDEX` statements; PostgreSQL creates ' +
      'the index of every primary and unique key on top |',
  );
  lines.push(
    `| Tables without a difference | - | ${result.identicalTables} | ` +
      `${result.differences.size} table(s) differ |`,
  );
  lines.push('');

  const missing = [];
  for (const [table, entries] of result.differences) {
    for (const entry of entries) {
      if (entry.kind === 'missing table' || entry.kind === 'extra table') missing.push(table);
    }
  }
  if (missing.length === 0) {
    lines.push('Every table of the MySQL source exists in PostgreSQL and the other way round.');
    lines.push('');
  }

  lines.push('## Differences');
  lines.push('');
  if (result.differences.size === 0) {
    lines.push('_none_');
    lines.push('');
  } else {
    for (const [table, entries] of result.differences) {
      lines.push(`### \`${table}\``);
      lines.push('');
      lines.push('| Column | Kind | MySQL source | PostgreSQL |');
      lines.push('|---|---|---|---|');
      for (const entry of entries) {
        lines.push(
          `| \`${entry.column}\` | ${entry.kind} | ${dash(entry.mysql)} | ${dash(entry.postgres)} |`,
        );
      }
      lines.push('');
    }
  }

  lines.push('## Source defects');
  lines.push('');
  if (result.defects.length === 0) {
    lines.push('_none_');
    lines.push('');
  } else {
    lines.push('| Id | Table | Column | Finding |');
    lines.push('|---|---|---|---|');
    for (const defect of result.defects) {
      lines.push(`| ${defect.id} | \`${defect.table}\` | \`${defect.column}\` | ${defect.finding} |`);
    }
    lines.push('');
  }

  lines.push('## Deliberate divergences');
  lines.push('');
  lines.push('| MySQL | PostgreSQL | Why |');
  lines.push('|---|---|---|');
  for (const [mysql, postgres, why] of DIVERGENCES) {
    lines.push(`| ${mysql} | ${postgres} | ${why} |`);
  }
  lines.push('');

  return lines.join('\n');
}

/** Read the catalogue from the live database, falling back to the dump. */
async function loadCatalogue(source) {
  if (source === 'file') {
    return { catalogue: JSON.parse(fs.readFileSync(CATALOGUE, 'utf8')), source: 'file' };
  }
  try {
    const client = await connectLive();
    try {
      const catalogue = await dumpLiveCatalogue(client);
      return { catalogue, source: 'live' };
    } finally {
      await client.end();
    }
  } catch (err) {
    if (source === 'live') throw err;
    if (!fs.existsSync(CATALOGUE)) throw err;
    return { catalogue: JSON.parse(fs.readFileSync(CATALOGUE, 'utf8')), source: 'file' };
  }
}

/** Read the MySQL reference document of `tools/translate.py`. */
function loadReference() {
  if (!fs.existsSync(REFERENCE)) {
    throw new Error(
      `${REFERENCE} is missing - run \`python tools/translate.py\` before this tool`,
    );
  }
  return JSON.parse(fs.readFileSync(REFERENCE, 'utf8'));
}

/** Compare a rendered document with the file on disk and report the first lines. */
function reportDiff(out, existing, text) {
  console.error(`DIFF - ${path.relative(ROOT, out)} is out of date`);
  if (existing === null) {
    console.error('the file does not exist');
    return;
  }
  const a = existing.split('\n');
  const b = text.split('\n');
  let shown = 0;
  for (let i = 0; i < Math.max(a.length, b.length) && shown < 20; i++) {
    if (a[i] !== b[i]) {
      console.error(`  line ${i + 1}: on disk ${JSON.stringify(a[i] ?? null)}`);
      console.error(`           rendered ${JSON.stringify(b[i] ?? null)}`);
      shown += 1;
    }
  }
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--help') || args.includes('-h')) {
    console.log(USAGE);
    process.exit(0);
  }
  const asJson = args.includes('--json');
  const check = args.includes('--check');
  const outIndex = args.indexOf('--out');
  const out = outIndex === -1 ? DEFAULT_OUT : path.resolve(ROOT, args[outIndex + 1]);
  const reconIndex = args.indexOf('--reconciliation-out');
  const reconOut =
    reconIndex === -1 ? DEFAULT_RECONCILIATION_OUT : path.resolve(ROOT, args[reconIndex + 1]);
  const sourceIndex = args.indexOf('--source');
  const source = sourceIndex === -1 ? 'auto' : args[sourceIndex + 1];
  if (!['auto', 'live', 'file'].includes(source)) {
    console.error(`unknown --source ${source} (expected auto, live or file)`);
    process.exit(2);
  }

  const loaded = await loadCatalogue(source);
  const reference = loadReference();

  const documents = [
    { out, text: render(loaded.catalogue) },
    { out: reconOut, text: renderReconciliation(loaded.catalogue, reference) },
  ];
  for (const document of documents) {
    document.existing = fs.existsSync(document.out)
      ? fs.readFileSync(document.out, 'utf8')
      : null;
    document.unchanged = document.existing === document.text;
  }

  const reconciliation = reconcile(loaded.catalogue, reference);

  if (asJson) {
    console.log(
      JSON.stringify(
        {
          source: loaded.source,
          unchanged: documents.every((document) => document.unchanged),
          outputs: documents.map((document) => ({
            output: path.relative(ROOT, document.out),
            unchanged: document.unchanged,
          })),
          counts: loaded.catalogue.counts,
          reconciliation: {
            mysql: reconciliation.counts.mysql,
            postgres: reconciliation.counts.pg,
            differingTables: reconciliation.differences.size,
            sourceDefects: reconciliation.defects.length,
          },
        },
        null,
        1,
      ),
    );
    process.exit(documents.every((document) => document.unchanged) ? 0 : 1);
  }

  if (check) {
    let failed = false;
    for (const document of documents) {
      if (document.unchanged) {
        console.log(`OK - ${path.relative(ROOT, document.out)} is up to date (source: ${loaded.source})`);
      } else {
        failed = true;
        reportDiff(document.out, document.existing, document.text);
      }
    }
    process.exit(failed ? 1 : 0);
  }

  for (const document of documents) {
    fs.mkdirSync(path.dirname(document.out), { recursive: true });
    fs.writeFileSync(document.out, document.text, 'utf8');
    console.log(
      `wrote ${path.relative(ROOT, document.out)} (${fs.statSync(document.out).size} bytes, source: ${loaded.source})`,
    );
  }
  const c = loaded.catalogue.counts;
  console.log(
    `tables ${c.tables}, views ${c.views}, functions ${c.functions}, triggers ${c.triggers}, ` +
      `policies ${c.policies}, RLS on ${c.rls_tables}`,
  );
  console.log(
    `indexes ${c.indexes}, sequences ${c.sequences}, domains ${c.domains}, ` +
      `enums ${c.enums}, composites ${c.composites}, grants ${c.grants}`,
  );
  console.log(
    `reconciliation: ${reconciliation.counts.mysql.tables} tables, ` +
      `${reconciliation.counts.mysql.columns} columns, ` +
      `${reconciliation.identicalTables} identical, ` +
      `${reconciliation.differences.size} differing, ` +
      `${reconciliation.defects.length} source defect(s)`,
  );
  for (const [table, entries] of reconciliation.differences) {
    for (const entry of entries) {
      console.log(`  ${table}: ${entry.column} (${entry.kind})`);
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
