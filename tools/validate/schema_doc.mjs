/**
 * Schema documentation.
 *
 *   node tools/validate/schema_doc.mjs [--check] [--out PATH] [--json]
 *                                       [--reconciliation-out PATH]
 *                                       [--source auto|live|file]
 *
 * Renders two documents:
 *
 *   docs/SCHEMA.md                 the schema reference: every table with its
 *                                  columns, constraints and indexes, then the
 *                                  views, functions, triggers and policies of
 *                                  each schema, and finally the domains and
 *                                  the sequences.
 *
 *   docs/SCHEMA_RECONCILIATION.md  the reconciliation of the MySQL source
 *                                  (`SIMS-DatabaseWithoutLessonPlan.sql`) with
 *                                  the PostgreSQL schema the migrations build:
 *                                  every table, column, type, nullability
 *                                  flag, default and named constraint of the
 *                                  source is looked up in the rebuilt
 *                                  database.
 *
 * The catalogue is read from the database (`--source live`, the session is
 * switched to read-only) or from the committed dump
 * `tools/catalogue/live_catalogue.json` (`--source file`).  `--source auto`
 * (the default) asks the database first and falls back to the committed dump
 * when the project cannot be reached, so the tool also works offline.
 *
 * The MySQL side of the reconciliation comes from `tools/catalogue/
 * mysql_reference.json`, the normalised document that `tools/translate.py`
 * writes from the MySQL source.
 *
 * `--check` does not write: it renders the documents in memory and compares
 * them with the files on disk, exiting non-zero when one of them differs.
 * That makes the documents build artefacts that cannot silently drift away
 * from the schema.
 */
