#!/usr/bin/env python3
"""Apply the migration set to the Supabase project.

Usage:
    python tools/apply_migrations.py [--apply] [--dry-run] [--dir PATH]
                                     [--file NAME]... [--force] [--json]

Without `--apply` the tool only prints the plan: which migration files exist,
which of them the project has already applied and which ones would run.  It
never writes to the database in that mode.  `--apply` is the only way to make
it write, and it is deliberately explicit.

The applied files are tracked in `sims_private.schema_migration`:

    filename      the name of the file in `supabase/migrations/`
    checksum      the SHA-256 of the file when it was applied
    applied_at    when it was applied
    applied_by    the database user that applied it
    execution_ms  how long it took

Every file is applied in its own transaction.  When a statement fails the
transaction is rolled back, so the database keeps the state it had before the
file was started, and the tool reports the file, the number of the statement
inside the file and the text of that statement together with the error the
database returned.

Connection settings (the environment wins over the defaults):

    SUPABASE_DB_HOST      aws-0-ap-southeast-1.pooler.supabase.com
    SUPABASE_DB_PORT      5432
    SUPABASE_DB_NAME      postgres
    SUPABASE_DB_USER      postgres.khqqfgqvwdxlqkncwtmh
    SUPABASE_DB_PASSWORD  <the project password>
    SUPABASE_DB_SSLMODE   require

`SIMS_DB_*` is accepted as an alias for `SUPABASE_DB_*`.

Exit code 0 means "the plan is clean" or "every migration was applied", 1 means
"a migration failed" and 2 means "the tool was not configured correctly".
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

try:
    import psycopg2
except ImportError:  # pragma: no cover - the dependency is documented
    print("psycopg2 is required: pip install psycopg2-binary", file=sys.stderr)
    raise

ROOT = Path(__file__).resolve().parent.parent
MIGRATIONS = ROOT / "supabase" / "migrations"

DEFAULT_HOST = "aws-0-ap-southeast-1.pooler.supabase.com"
DEFAULT_PORT = 5432
DEFAULT_DB = "postgres"
DEFAULT_USER = "postgres.khqqfgqvwdxlqkncwtmh"
DEFAULT_PASSWORD = ""
DEFAULT_SSLMODE = "require"

TRACKING_SCHEMA = "sims_private"
TRACKING_TABLE = "schema_migration"

#: The statement that creates the tracking table.
TRACKING_DDL = f"""
CREATE SCHEMA IF NOT EXISTS {TRACKING_SCHEMA};

CREATE TABLE IF NOT EXISTS {TRACKING_SCHEMA}.{TRACKING_TABLE} (
  migration_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  filename text NOT NULL UNIQUE,
  checksum text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now(),
  applied_by text NOT NULL DEFAULT current_user,
  execution_ms integer NOT NULL DEFAULT 0
);
"""

DOLLAR_TAG = re.compile(r"\$[A-Za-z_][A-Za-z_0-9]*\$|\$\$")


# ---------------------------------------------------------------------------
# configuration
# ---------------------------------------------------------------------------
def dsn() -> dict:
    """The connection settings of the project."""

    def pick(name: str, fallback):
        for prefix in ("SUPABASE_DB_", "SIMS_DB_"):
            value = os.environ.get(prefix + name)
            if value:
                return value
        return fallback

    return dict(
        host=pick("HOST", DEFAULT_HOST),
        port=int(pick("PORT", DEFAULT_PORT)),
        dbname=pick("NAME", DEFAULT_DB),
        user=pick("USER", DEFAULT_USER),
        password=pick("PASSWORD", DEFAULT_PASSWORD),
        sslmode=pick("SSLMODE", DEFAULT_SSLMODE),
    )


def connect(readonly: bool = False):
    """Open a connection to the project."""
    settings = dsn()
    if not settings["password"]:
        raise SystemExit(
            "SUPABASE_DB_PASSWORD is not set (or SIMS_DB_PASSWORD). The password "
            "is never stored in the repository - put it into .env.local."
        )
    conn = psycopg2.connect(**settings)
    if readonly:
        conn.set_session(readonly=True, autocommit=True)
    else:
        conn.set_session(autocommit=False)
    return conn


# ---------------------------------------------------------------------------
# splitting a migration file into statements
# ---------------------------------------------------------------------------
def split_statements(sql: str) -> list[str]:
    """Split a SQL file into its statements.

    The splitter understands single quoted strings, double quoted identifiers,
    dollar quoted strings (`$$` and `$tag$`), line comments and (nested) block
    comments, so that a semicolon inside a function body does not end a
    statement.
    """
    statements: list[str] = []
    buf: list[str] = []
    i = 0
    n = len(sql)

    while i < n:
        c = sql[i]

        # line comment
        if c == "-" and sql[i + 1 : i + 2] == "-":
            j = sql.find("\n", i)
            j = n if j == -1 else j
            buf.append(sql[i:j])
            i = j
            continue

        # block comment (PostgreSQL nests them)
        if c == "/" and sql[i + 1 : i + 2] == "*":
            depth = 1
            j = i + 2
            while j < n and depth:
                if sql[j : j + 2] == "/*":
                    depth += 1
                    j += 2
                elif sql[j : j + 2] == "*/":
                    depth -= 1
                    j += 2
                else:
                    j += 1
            buf.append(sql[i:j])
            i = j
            continue

        # single quoted string, with the E'' escape syntax
        if c == "'" or (c in "eE" and sql[i + 1 : i + 2] == "'"):
            start = i
            if c in "eE":
                i += 1
            i += 1
            while i < n:
                if sql[i] == "\\" and c in "eE":
                    i += 2
                    continue
                if sql[i] == "'":
                    if sql[i + 1 : i + 2] == "'":
                        i += 2
                        continue
                    i += 1
                    break
                i += 1
            buf.append(sql[start:i])
            continue

        # double quoted identifier
        if c == '"':
            j = i + 1
            while j < n:
                if sql[j] == '"':
                    if sql[j + 1 : j + 2] == '"':
                        j += 2
                        continue
                    break
                j += 1
            buf.append(sql[i : j + 1])
            i = j + 1
            continue

        # dollar quoted string
        if c == "$":
            match = DOLLAR_TAG.match(sql, i)
            if match:
                tag = match.group(0)
                end = sql.find(tag, i + len(tag))
                if end == -1:
                    raise ValueError(f"unterminated dollar quote {tag}")
                buf.append(sql[i : end + len(tag)])
                i = end + len(tag)
                continue

        # statement separator
        if c == ";":
            statements.append("".join(buf).strip())
            buf = []
            i += 1
            continue

        buf.append(c)
        i += 1

    tail = "".join(buf).strip()
    if tail:
        statements.append(tail)
    return [s for s in statements if s]


def checksum(text: str) -> str:
    """The SHA-256 of a migration file."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# the plan
# ---------------------------------------------------------------------------
def migration_files(directory: Path, only: list[str]) -> list[Path]:
    """The migration files to consider, in the order they are applied."""
    files = sorted(p for p in directory.glob("*.sql") if p.is_file())
    if not only:
        return files
    wanted = set(only)
    unknown = wanted - {p.name for p in files}
    if unknown:
        raise SystemExit(f"unknown migration file(s): {', '.join(sorted(unknown))}")
    return [p for p in files if p.name in wanted]


def applied_files(conn) -> dict:
    """The migrations the project has already applied."""
    cur = conn.cursor()
    cur.execute(
        "SELECT to_regclass(%s) IS NOT NULL",
        (f"{TRACKING_SCHEMA}.{TRACKING_TABLE}",),
    )
    if not cur.fetchone()[0]:
        return {}
    cur.execute(
        f"SELECT filename, checksum, applied_at FROM {TRACKING_SCHEMA}.{TRACKING_TABLE} "
        "ORDER BY filename"
    )
    return {
        row[0]: {"checksum": row[1], "applied_at": row[2].isoformat()} for row in cur.fetchall()
    }


def build_plan(files: list[Path], applied: dict) -> list[dict]:
    """The plan: one entry per migration file."""
    plan = []
    for path in files:
        text = path.read_text(encoding="utf-8")
        sum_ = checksum(text)
        known = applied.get(path.name)
        if known is None:
            status = "pending"
        elif known["checksum"] != sum_:
            status = "changed"
        else:
            status = "applied"
        plan.append(
            {
                "file": path.name,
                "checksum": sum_,
                "status": status,
                "statements": len(split_statements(text)),
                "applied_at": known["applied_at"] if known else None,
            }
        )
    return plan


# ---------------------------------------------------------------------------
# applying
# ---------------------------------------------------------------------------
def apply_file(conn, path: Path, sum_: str) -> dict:
    """Apply one migration file in its own transaction.

    Returns a dictionary with the number of statements that ran and how long
    the file took.  When a statement fails the transaction is rolled back and
    the error is raised as a `MigrationError`.
    """
    text = path.read_text(encoding="utf-8")
    statements = split_statements(text)
    started = time.time()
    cur = conn.cursor()
    try:
        for number, statement in enumerate(statements, start=1):
            try:
                cur.execute(statement)
            except Exception as exc:  # the database rejected the statement
                conn.rollback()
                raise MigrationError(path, number, statement, exc) from exc
        cur.execute(
            f"INSERT INTO {TRACKING_SCHEMA}.{TRACKING_TABLE} "
            "(filename, checksum, applied_by, execution_ms) VALUES (%s, %s, current_user, %s) "
            "ON CONFLICT (filename) DO UPDATE SET checksum = EXCLUDED.checksum, "
            "applied_at = now(), applied_by = EXCLUDED.applied_by, "
            "execution_ms = EXCLUDED.execution_ms",
            (path.name, sum_, int((time.time() - started) * 1000)),
        )
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    return {"file": path.name, "statements": len(statements), "ms": int((time.time() - started) * 1000)}


class MigrationError(Exception):
    """A migration statement failed."""

    def __init__(self, path: Path, number: int, statement: str, cause: Exception):
        self.path = path
        self.number = number
        self.statement = statement
        self.cause = cause
        super().__init__(str(cause))

    def report(self) -> str:
        """The report of the failure."""
        first_line = self.statement.strip().splitlines()[0] if self.statement.strip() else ""
        if len(first_line) > 160:
            first_line = first_line[:157] + "..."
        code = getattr(self.cause, "pgcode", None)
        lines = [
            f"FAILED in {self.path.name}, statement {self.number}",
            f"  statement: {first_line}",
            f"  error    : {self.cause}",
        ]
        if code:
            lines.insert(2, f"  sqlstate : {code}")
        lines.append("  the transaction of the file was rolled back")
        return "\n".join(lines)


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--apply",
        action="store_true",
        help="apply the pending migrations (without it the tool only prints the plan)",
    )
    ap.add_argument("--dry-run", action="store_true", help="print the plan and stop (the default)")
    ap.add_argument("--dir", default=str(MIGRATIONS), help="the directory with the migration files")
    ap.add_argument(
        "--file",
        action="append",
        default=[],
        help="only consider this migration file (repeatable)",
    )
    ap.add_argument(
        "--force",
        action="store_true",
        help="apply a file again when it changed since it was applied",
    )
    ap.add_argument(
        "--baseline-before",
        default="",
        metavar="FILENAME",
        help="record every migration file that sorts before FILENAME as applied, "
        "without running it.  Use it when the database already carries that "
        "schema but has no tracking table.",
    )
    ap.add_argument("--json", action="store_true", help="machine readable report")
    args = ap.parse_args()

    directory = Path(args.dir)
    if not directory.is_dir():
        print(f"the migration directory does not exist: {directory}", file=sys.stderr)
        return 2

    files = migration_files(directory, args.file)
    if not files:
        print(f"no migration files in {directory}", file=sys.stderr)
        return 2

    # --- the plan ------------------------------------------------------------
    applied: dict = {}
    connection_error = None
    try:
        conn = connect(readonly=True)
        try:
            applied = applied_files(conn)
        finally:
            conn.close()
    except Exception as exc:  # the project cannot be reached
        connection_error = str(exc).strip().splitlines()[0]

    plan = build_plan(files, applied)
    pending = [entry for entry in plan if entry["status"] == "pending"]
    changed = [entry for entry in plan if entry["status"] == "changed"]

    if not args.apply:
        if args.json:
            print(
                json.dumps(
                    {
                        "mode": "dry-run",
                        "database": dsn()["dbname"],
                        "files": plan,
                        "pending": len(pending),
                        "changed": len(changed),
                    },
                    indent=1,
                )
            )
            return 0
        print(f"migration directory: {directory}")
        print(f"database           : {dsn()['dbname']} on {dsn()['host']}")
        if connection_error:
            print(f"the project is not reachable ({connection_error}), the plan is local only")
        print(f"{len(plan)} migration file(s), {len(pending)} pending, {len(changed)} changed")
        for entry in plan:
            marker = {"pending": "pending", "applied": "applied", "changed": "CHANGED"}[entry["status"]]
            print(f"  {marker:<8} {entry['file']} ({entry['statements']} statement(s))")
        print("")
        print("dry run: nothing was written. Use --apply to apply the pending migrations.")
        return 0

    # --- apply ---------------------------------------------------------------
    if changed and not args.force:
        print(
            "these files changed since they were applied, use --force to apply them again:",
            file=sys.stderr,
        )
        for entry in changed:
            print(f"  {entry['file']}", file=sys.stderr)
        return 2

    conn = connect(readonly=False)
    applied_now = []
    baselined_now = []
    try:
        cur = conn.cursor()
        cur.execute(TRACKING_DDL)
        conn.commit()

        if args.baseline_before:
            # The database already carries this schema, but there is no
            # tracking table to say so.  Record the files without running
            # them, so that a later run does not try to create the objects
            # again.
            for entry in plan:
                if entry["file"] >= args.baseline_before or entry["status"] == "applied":
                    continue
                cur.execute(
                    f"INSERT INTO {TRACKING_SCHEMA}.{TRACKING_TABLE} "
                    "(filename, checksum, applied_by, execution_ms) "
                    "VALUES (%s, %s, current_user, 0) "
                    "ON CONFLICT (filename) DO UPDATE SET checksum = EXCLUDED.checksum, "
                    "applied_at = now(), applied_by = EXCLUDED.applied_by, execution_ms = 0",
                    (entry["file"], entry["checksum"]),
                )
                baselined_now.append(entry["file"])
            conn.commit()
            print(
                f"baselined {len(baselined_now)} migration file(s) as applied "
                f"(nothing was executed)"
            )
            for name in baselined_now:
                print(f"  baseline  {name}")

        for entry in plan:
            if entry["status"] == "applied" or entry["file"] in baselined_now:
                continue
            path = directory / entry["file"]
            try:
                result = apply_file(conn, path, entry["checksum"])
            except MigrationError as exc:
                if args.json:
                    print(
                        json.dumps(
                            {
                                "mode": "apply",
                                "applied": applied_now,
                                "failed": {
                                    "file": exc.path.name,
                                    "statement": exc.number,
                                    "text": exc.statement,
                                    "error": str(exc.cause),
                                },
                            },
                            indent=1,
                        )
                    )
                else:
                    print(exc.report(), file=sys.stderr)
                    print(
                        f"{len(applied_now)} migration file(s) were applied before the failure",
                        file=sys.stderr,
                    )
                return 1
            applied_now.append(result)
            if not args.json:
                print(
                    f"applied {result['file']} ({result['statements']} statement(s), "
                    f"{result['ms']} ms)"
                )
    finally:
        conn.close()

    if args.json:
        print(
            json.dumps(
                {
                    "mode": "apply",
                    "applied": applied_now,
                    "baselined": baselined_now,
                },
                indent=1,
            )
        )
    else:
        print(f"{len(applied_now)} migration file(s) applied")
    return 0


if __name__ == "__main__":
    sys.exit(main())
