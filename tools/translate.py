def translate(source: Path) -> dict:
    """Parse the MySQL source and return the normalised reference document."""
    text = source.read_text(encoding="utf-8")
    sections = module_sections(text)

    tables: list[dict] = []
    indexes: list[dict] = []
    views: list[dict] = []
    triggers: list[dict] = []
    alters: list[dict] = []
    inserts: list[dict] = []
    ignored: list[dict] = []

    for statement, line in split_statements(text):
        module = module_for(line, sections)
        if CREATE_TABLE_RE.match(statement):
            tables.append(parse_table(statement, line, module))
        elif CREATE_INDEX_RE.match(statement):
            indexes.append(parse_index(statement, line, module))
        elif CREATE_VIEW_RE.match(statement):
            views.append(parse_view(statement, line, module))
        elif CREATE_TRIGGER_RE.match(statement):
            triggers.append(parse_trigger(statement, line, module))
        elif ALTER_TABLE_RE.match(statement):
            alters.append(parse_alter(statement, line, module))
        elif INSERT_RE.match(statement):
            inserts.append(parse_insert(statement, line, module))
        elif re.match(r"^(SET|DELIMITER|USE|START|COMMIT|ROLLBACK)\b", statement, re.I):
            ignored.append({"line": line, "statement": statement[:120]})
        else:
            ignored.append({"line": line, "statement": statement[:120]})

    # `ALTER TABLE ... ADD COLUMN` adds columns that the CREATE TABLE does
    # not have.  They are attached to the table so that the reference
    # document describes the same columns as the source.
    for alter in alters:
        if not alter["added_columns"]:
            continue
        target = next((t for t in tables if t["name"] == alter["table"]), None)
        if target is None:
            continue
        known = {c["name"] for c in target["columns"]}
        for column in alter["added_columns"]:
            if column["name"] in known:
                # the source defines the column twice (SD-1); MySQL aborts,
                # the migration set adds it only once
                column["duplicate"] = True
                target["duplicate_columns"].append(column["name"])
                continue
            known.add(column["name"])
            column["added_by_alter"] = True
            target["columns"].append(column)

    # `ALTER TABLE ... ADD CONSTRAINT ... FOREIGN KEY` adds a foreign key
    # that the CREATE TABLE does not have.
    for alter in alters:
        if not alter["foreign_key"]:
            continue
        target = next((t for t in tables if t["name"] == alter["table"]), None)
        if target is None:
            continue
        foreign_key = dict(alter["foreign_key"])
        foreign_key["added_by_alter"] = True
        target["foreign_keys"].append(foreign_key)

    # the module index: which objects live in which section
    module_index = []
    for section in sections:
        module_index.append({
            "number": section["number"],
            "title": section["title"],
            "line": section["line"],
            "tables": [t["name"] for t in tables if t["module"] == section["number"]],
            "indexes": [i["name"] for i in indexes if i["module"] == section["number"]],
            "views": [v["name"] for v in views if v["module"] == section["number"]],
            "triggers": [t["name"] for t in triggers if t["module"] == section["number"]],
        })

    total_columns = sum(len(t["columns"]) for t in tables)
    total_fks = sum(len(t["foreign_keys"]) for t in tables)
    return {
        "source": source.name,
        "generator": "tools/translate.py",
        "target": "postgresql",
        "contract": (
            "Normalised description of the MySQL reference schema. "
            "tools/build_migrations.py reads this file next to "
            "tools/catalogue/live_catalogue.json."
        ),
        "modules": module_index,
        "tables": tables,
        "indexes": indexes,
        "views": views,
        "triggers": triggers,
        "alterations": alters,
        "inserts": inserts,
        "postgresql": {
            "tables": {t["name"]: render_table(t) for t in tables},
            "indexes": [render_index(i) for i in indexes],
            "views": [render_view(v) for v in views],
            "triggers": [render_trigger(t) for t in triggers],
            "inserts": [render_insert(i) for i in inserts],
            "touch_triggers": render_touch_triggers(tables),
        },
        "counts": {
            "modules": len(sections),
            "tables": len(tables),
            "columns": total_columns,
            "indexes": len(indexes),
            "unique_constraints": sum(len(t["unique_constraints"]) for t in tables),
            "foreign_keys": total_fks,
            "views": len(views),
            "triggers": len(triggers),
            "insert_statements": len(inserts),
            "insert_rows": sum(i["rows"] for i in inserts),
            "insert_from_select": sum(1 for i in inserts if i["source"] == "SELECT"),
            "ignored_statements": len(ignored),
        },
    }


def render(document: dict) -> str:
    return json.dumps(document, indent=1, sort_keys=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--source", default=str(DEFAULT_SOURCE),
                    help="the MySQL reference file to translate")
    ap.add_argument("--out", default=str(DEFAULT_OUT),
                    help="where the normalised JSON document is written")
    ap.add_argument("--check", action="store_true",
                    help="do not write, only report whether the document is up to date")
    args = ap.parse_args()

    source = Path(args.source)
    if not source.exists():
        raise SystemExit(f"MySQL source not found: {source}")

    document = translate(source)
    text = render(document)
    out = Path(args.out)

    if args.check:
        existing = out.read_text(encoding="utf-8") if out.exists() else None
        if existing == text:
            print(f"OK - {out} is up to date")
            return 0
        print(f"DIFF - {out} is out of date")
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    counts = document["counts"]
    print(f"wrote {out} ({out.stat().st_size} bytes)")
    print(
        "translated {tables} tables, {columns} columns, {indexes} indexes, "
        "{foreign_keys} foreign keys, {views} views, {triggers} triggers, "
        "{insert_statements} insert statements ({insert_rows} rows) "
        "from {modules} module sections".format(**counts)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
