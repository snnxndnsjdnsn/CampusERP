def unquote(name: str) -> str:
    name = name.strip()
    if name.startswith("`") and name.endswith("`"):
        name = name[1:-1]
    return name.replace("``", "`")


def clean_list(text: str) -> list[str]:
    """Split a MySQL column list into the individual column names."""
    return [unquote(part) for part in split_top_level(text) if part.strip()]


def parse_column(definition: str) -> dict:
    """Parse one column definition of a `CREATE TABLE` body."""
    definition = definition.strip()
    match = re.match(r"^(?P<name>`?[A-Za-z_][\w$]*`?)\s+(?P<rest>.*)$", definition, re.S)
    if not match:
        return {"name": definition, "type": "text", "mysql_type": "", "error": "unparsable"}
    name = unquote(match.group("name"))
    rest = match.group("rest").strip()

    type_match = TYPE_RE.match(rest)
    if type_match:
        mysql_type = rest[: type_match.end()].strip()
        remainder = rest[type_match.end() :].strip()
    else:
        mysql_type = rest
        remainder = ""
    pg, domain, note = postgres_type(mysql_type)

    column = {
        "name": name,
        "mysql_type": mysql_type,
        "type": pg,
        "domain": domain,
        "nullable": True,
        "default": None,
        "auto_increment": False,
        "primary_key": False,
        "unique": False,
        "comment": None,
        "on_update": None,
        "generated": None,
        "references": None,
        "check": None,
    }
    if note:
        column["note"] = note

    for attr in COLUMN_ATTR_RE.finditer(remainder):
        if attr.group("not_null"):
            column["nullable"] = False
        elif attr.group("null"):
            column["nullable"] = True
        elif attr.group("auto_increment"):
            column["auto_increment"] = True
        elif attr.group("primary_key"):
            column["primary_key"] = True
            column["nullable"] = False
        elif attr.group("unique"):
            column["unique"] = True
        elif attr.group("default"):
            column["default"] = attr.group("dval").strip()
        elif attr.group("on_update"):
            column["on_update"] = attr.group("oval").strip()
        elif attr.group("comment"):
            column["comment"] = attr.group("comment")[len("COMMENT"):].strip().strip("'")
        elif attr.group("generated"):
            column["generated"] = attr.group("gexpr").strip()
        elif attr.group("references"):
            column["references"] = {
                "table": unquote(attr.group("rtable")),
                "columns": clean_list(attr.group("rcols")),
            }
        elif attr.group("check"):
            column["check"] = attr.group("cexpr").strip()
    return column


def parse_table(statement: str, line: int, module: dict | None) -> dict:
    """Parse a `CREATE TABLE` statement."""
    match = CREATE_TABLE_RE.match(statement)
    name = unquote(match.group("name"))
    open_paren = match.end() - 1
    close = find_matching(statement, open_paren)
    body = statement[open_paren + 1: close]
    options = statement[close + 1:].strip()

    table = {
        "name": name,
        "line": line,
        "module": module["number"] if module else None,
        "module_title": module["title"] if module else None,
        "options": options,
        "columns": [],
        "primary_key": [],
        "unique_constraints": [],
        "foreign_keys": [],
        "indexes": [],
        "checks": [],
        "duplicate_columns": [],
    }

    for item in split_top_level(body):
        constraint = CONSTRAINT_RE.match(item)
        if constraint:
            item = constraint.group("body").strip()
            cname = unquote(constraint.group("name"))
        else:
            cname = None

        fk = FOREIGN_KEY_RE.match(item)
        if fk:
            table["foreign_keys"].append({
                "name": cname,
                "columns": clean_list(fk.group("cols")),
                "references": {
                    "table": unquote(fk.group("table")),
                    "columns": clean_list(fk.group("rcols")),
                },
            })
            continue
        pk = PRIMARY_KEY_RE.match(item)
        if pk:
            table["primary_key"] = clean_list(pk.group("cols"))
            continue
        uq = UNIQUE_RE.match(item)
        if uq:
            table["unique_constraints"].append({
                "name": cname or unquote(uq.group("name") or ""),
                "columns": clean_list(uq.group("cols")),
            })
            continue
        key = KEY_RE.match(item)
        if key:
            table["indexes"].append({
                "name": cname or unquote(key.group("name") or ""),
                "columns": clean_list(key.group("cols")),
            })
            continue
        check = CHECK_RE.match(item)
        if check:
            table["checks"].append({"name": cname, "expression": check.group("expr").strip()})
            continue

        column = parse_column(item)
        if column.get("primary_key") and not table["primary_key"]:
            table["primary_key"] = [column["name"]]
        if column.get("unique"):
            table["unique_constraints"].append({
                "name": None,
                "columns": [column["name"]],
            })
        if column.get("references"):
            table["foreign_keys"].append({
                "name": None,
                "columns": [column["name"]],
                "references": column["references"],
            })
        table["columns"].append(column)
    return table


def parse_index(statement: str, line: int, module: dict | None) -> dict:
    match = CREATE_INDEX_RE.match(statement)
    open_paren = match.end() - 1
    close = find_matching(statement, open_paren)
    columns = clean_list(statement[open_paren + 1: close])
    return {
        "name": unquote(match.group("name")),
        "table": unquote(match.group("table")),
        "unique": bool(match.group("unique")),
        "columns": columns,
        "line": line,
        "module": module["number"] if module else None,
    }


def parse_view(statement: str, line: int, module: dict | None) -> dict:
    match = CREATE_VIEW_RE.match(statement)
    body = statement[match.end():].strip()
    return {
        "name": unquote(match.group("name")),
        "line": line,
        "module": module["number"] if module else None,
        "body": body,
    }


def parse_trigger(statement: str, line: int, module: dict | None) -> dict:
    match = CREATE_TRIGGER_RE.match(statement)
    head = statement[: match.end()].strip()
    tail = statement[match.end():].strip()
    table = None
    timing = None
    event = None
    m = re.search(
        r"\b(BEFORE|AFTER)\s+(INSERT|UPDATE|DELETE)\s+ON\s+`?(\w+)`?", tail, re.I
    )
    if m:
        timing, event, table = m.group(1).upper(), m.group(2).upper(), m.group(3)
    return {
        "name": unquote(match.group("name")),
        "table": table,
        "timing": timing,
        "event": event,
        "line": line,
        "module": module["number"] if module else None,
        "definition": head + " " + tail,
    }


def parse_added_columns(action: str) -> list[dict]:
    """The columns an `ALTER TABLE ... ADD COLUMN` statement adds.

    MySQL allows several `ADD COLUMN` clauses in one statement; they are
    separated by commas, but a comma can also be part of a column default, so
    the action is cut at the `ADD COLUMN` keywords first.
    """
    parts = re.split(r"ADD\s+(?:COLUMN\s+)?", action, flags=re.I)
    columns: list[dict] = []
    for part in parts[1:]:
        definition = part.strip()
        if not definition:
            continue
        # a trailing `AFTER <column>` / `FIRST` belongs to MySQL only
        definition = re.sub(
            r"\s+(?:AFTER\s+`?\w+`?|FIRST)\s*$", "", definition, flags=re.I
        )
        if not definition or re.match(
            r"^(?:CONSTRAINT|FOREIGN\s+KEY|PRIMARY\s+KEY|UNIQUE)\b", definition, re.I
        ):
            continue
        columns.append(parse_column(definition))
    return columns


def parse_alter(statement: str, line: int, module: dict | None) -> dict:
    """Parse an `ALTER TABLE` statement."""
    match = ALTER_TABLE_RE.match(statement)
    # the action often spans several lines; it is normalised so that the
    # keyword searches below see a single line
    action = re.sub(r"\s+", " ", match.group("action").strip())
    cname = None
    cmatch = re.search(r"ADD\s+CONSTRAINT\s+`?(\w+)`?", action, re.I)
    if cmatch:
        cname = cmatch.group(1)
    foreign_key = None
    if re.search(r"ADD\s+CONSTRAINT\b.*\bFOREIGN\s+KEY\b", action, re.I):
        fk = FOREIGN_KEY_IN_ALTER_RE.search(action)
        if fk:
            foreign_key = {
                "name": cname,
                "columns": clean_list(fk.group("cols")),
                "references": {
                    "table": unquote(fk.group("table")),
                    "columns": clean_list(fk.group("rcols")),
                },
            }
    return {
        "table": unquote(match.group("name")),
        "constraint": cname,
        "action": action,
        "adds_foreign_key": foreign_key is not None,
        "foreign_key": foreign_key,
        "added_columns": parse_added_columns(action),
        "line": line,
        "module": module["number"] if module else None,
    }


def count_value_tuples(text: str) -> int:
    """Number of `( ... )` tuples in the VALUES list of an INSERT statement."""
    values = re.search(r"\bVALUES\b", text, re.I)
    if not values:
        return 0
    i = values.end()
    n = len(text)
    depth = 0
    count = 0
    while i < n:
        c = text[i]
        if c in ("'", '"', "`"):
            i = _skip_quoted(text, i)
            continue
        if c == "(":
            if depth == 0:
                count += 1
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == ";" and depth == 0:
            break
        i += 1
    return count


def parse_insert(statement: str, line: int, module: dict | None) -> dict:
    match = INSERT_RE.match(statement)
    cols = match.group("cols")
    rest = match.group("rest")
    from_select = bool(re.match(r"^\s*SELECT\b", rest, re.I))
    return {
        "table": unquote(match.group("name")),
        "columns": clean_list(cols) if cols else [],
        "rows": 0 if from_select else count_value_tuples(rest),
        "source": "SELECT" if from_select else "VALUES",
        "statement": statement,
        "line": line,
        "module": module["number"] if module else None,
    }


# ---------------------------------------------------------------------------
# PostgreSQL rendering
# ---------------------------------------------------------------------------
# The identity columns use the plain integer type; the UNSIGNED range of the
# MySQL column is not enforced by the sequence (see docs/DATABASE_MIGRATION.md).
IDENTITY_DOMAIN = {
    "u8": "smallint",
    "u16": "smallint",
    "u24": "integer",
    "u32": "integer",
    "u64": "bigint",
}

TOUCH_FUNCTION = "sims_touch_updated_at"


def enum_values(mysql_type: str) -> list[str]:
    """The value list of a MySQL ``ENUM(...)`` type."""
    match = re.search(r"\((.*)\)", mysql_type, re.S)
    if not match:
        return []
    values = []
    for part in split_top_level(match.group(1)):
        part = part.strip()
        if part[:1] in ("'", '"'):
            values.append(part[1:-1].replace("''", "'"))
    return values


def render_table(table: dict) -> str:
    """The PostgreSQL ``CREATE TABLE`` of one MySQL table."""
    name = table["name"]
    lines: list[str] = []
    enum_checks: list[str] = []

    for col in table["columns"]:
        cname = unquote(col["name"])
        pg_type = col["type"]
        if col["auto_increment"]:
            pg_type = IDENTITY_DOMAIN.get(col.get("domain") or "", pg_type)
        piece = f"  {cname} {pg_type}"
        if col["auto_increment"]:
            piece += " GENERATED BY DEFAULT AS IDENTITY"
        if col["default"] is not None:
            piece += " DEFAULT " + translate_default(col["default"])
        if not col["nullable"]:
            piece += " NOT NULL"
        lines.append(piece)

        values = enum_values(col["mysql_type"])
        if values:
            listed = ", ".join(f"'{v}'::text" for v in values)
            enum_checks.append(
                f"  CONSTRAINT enum_{cname} CHECK ({cname} = ANY (ARRAY[{listed}]))"
            )

    if table["primary_key"]:
        cols = ", ".join(unquote(c) for c in table["primary_key"])
        lines.append(f"  CONSTRAINT {name}_pkey PRIMARY KEY ({cols})")

    for uq in table["unique_constraints"]:
        cols = ", ".join(unquote(c) for c in uq["columns"])
        cname = uq["name"] or (
            f"{name}_{'_'.join(unquote(c) for c in uq['columns'])}_key"
        )
        lines.append(f"  CONSTRAINT {cname} UNIQUE ({cols})")

    for fk in table["foreign_keys"]:
        cols = ", ".join(unquote(c) for c in fk["columns"])
        ref = fk["references"]
        rcols = ", ".join(unquote(c) for c in ref["columns"])
        cname = fk["name"] or (
            f"{name}_{'_'.join(unquote(c) for c in fk['columns'])}_fkey"
        )
        lines.append(
            f"  CONSTRAINT {cname} FOREIGN KEY ({cols}) "
            f"REFERENCES {unquote(ref['table'])} ({rcols})"
        )

    for chk in table["checks"]:
        expr = translate_expression(chk["expression"])
        cname = chk["name"] or f"{name}_check"
        lines.append(f"  CONSTRAINT {cname} CHECK ({expr})")

    lines.extend(enum_checks)

    body = ",\n".join(lines)
    return f"CREATE TABLE public.{name} (\n{body}\n);"


def render_index(index: dict) -> str:
    """The PostgreSQL ``CREATE INDEX`` of one MySQL index."""
    unique = "UNIQUE " if index["unique"] else ""
    cols = ", ".join(unquote(c) for c in index["columns"])
    return (
        f"CREATE {unique}INDEX {unquote(index['name'])} "
        f"ON public.{unquote(index['table'])} ({cols});"
    )


def render_view(view: dict) -> str:
    """The PostgreSQL ``CREATE VIEW`` of one MySQL view."""
    body = translate_expression(view["body"])
    return f"CREATE VIEW public.{unquote(view['name'])} AS\n{body};"


DECLARE_RE = re.compile(
    r"\bDECLARE\s+(?P<name>`?\w+`?)\s+"
    r"(?P<type>[A-Za-z]+(?:\s*\([^)]*\))?(?:\s+UNSIGNED)?)",
    re.I,
)


def translate_declarations(expr: str) -> str:
    """Translate the ``DECLARE`` statements of a MySQL trigger body.

    MySQL writes ``DECLARE v_total DECIMAL(12,2);`` inside the block, while
    PL/pgSQL wants the declarations in the ``DECLARE`` section of the block:
    the keyword is dropped and the type is translated.
    """
    def repl(match: re.Match) -> str:
        pg_type, _domain, _note = postgres_type(match.group("type"))
        return f"{match.group('name')} {pg_type}"

    return DECLARE_RE.sub(repl, expr)


def render_trigger(trigger: dict) -> str:
    """The PostgreSQL trigger function and trigger of one MySQL trigger.

    MySQL carries the body inside the trigger; PostgreSQL needs a function
    that the trigger calls.  The body is translated as well: ``SIGNAL
    SQLSTATE`` becomes ``RAISE EXCEPTION`` and ``ELSEIF`` becomes ``ELSIF``.
    """
    body = translate_expression(trigger["definition"])
    body = translate_declarations(body)
    body = re.sub(r"\bELSEIF\b", "ELSIF", body)

    match = re.search(
        r"\bBEGIN\b(?P<body>.*)\bEND\s*(?:\$\$)?\s*$", body, re.S | re.I
    )
    block = match.group("body").strip() if match else body.strip()
    # the declarations of the block belong into the DECLARE section
    block = re.sub(r"^\s*DECLARE\s+", "", block, flags=re.I)

    name = unquote(trigger["name"])
    table = trigger["table"]
    timing = trigger["timing"] or "BEFORE"
    event = trigger["event"] or "INSERT"
    return (
        f"CREATE OR REPLACE FUNCTION public.{name}_fn() RETURNS trigger\n"
        f"LANGUAGE plpgsql\n"
        f"AS $$\n"
        f"DECLARE\n"
        f"{block}\n"
        f"END;\n"
        f"$$;\n"
        f"CREATE TRIGGER {name}\n"
        f"{timing} {event} ON public.{table}\n"
        f"FOR EACH ROW EXECUTE FUNCTION public.{name}_fn();"
    )


def render_insert(insert: dict) -> str:
    """The PostgreSQL ``INSERT`` of one MySQL ``INSERT IGNORE``.

    MySQL's ``INSERT IGNORE`` silently skips a row that violates a unique
    constraint; PostgreSQL needs the conflict target to be spelled out.
    """
    statement = insert["statement"].strip().rstrip(";")
    statement = re.sub(
        r"^INSERT\s+IGNORE\s+INTO\b", "INSERT INTO", statement, flags=re.I
    )
    return statement + "\nON CONFLICT DO NOTHING;"


def render_touch_triggers(tables: list[dict]) -> list[str]:
    """The ``BEFORE UPDATE`` triggers that replace ``ON UPDATE CURRENT_TIMESTAMP``.

    MySQL keeps the column up to date inside the row update; PostgreSQL needs
    a trigger.  The live project uses one shared function
    (`sims_touch_updated_at()`) and one trigger per table.
    """
    out: list[str] = []
    for table in tables:
        for col in table["columns"]:
            if not col["on_update"]:
                continue
            out.append(
                f"CREATE TRIGGER trg_{table['name']}_touch_updated_at\n"
                f"BEFORE UPDATE ON public.{table['name']}\n"
                f"FOR EACH ROW EXECUTE FUNCTION {TOUCH_FUNCTION}();"
            )
    return out


