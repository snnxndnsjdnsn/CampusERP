#!/usr/bin/env python3
"""Translate the MySQL reference schema into a normalised PostgreSQL description.

WHAT THIS TOOL DOES
-------------------
`SIMS-DatabaseWithoutLessonPlan.sql` is the MySQL 8 reference schema of the
SIMS / College-ERP project (5648 lines, 213 `CREATE TABLE`, 40 numbered module
sections, 104 `CREATE INDEX`, 10 views, 16 triggers and 95 `INSERT INTO`
statements).  This script parses that file and writes a normalised JSON
description of the schema to

    tools/catalogue/mysql_reference.json

The document holds, for every table, its columns (name, MySQL type, PostgreSQL
type, nullability, default, auto-increment flag), its primary key, its unique
constraints, its foreign keys and its indexes; the indexes, views, triggers and
seed statements of the whole file; the module section every object belongs to;
and the PostgreSQL rendering of every object.

THE CONTRACT WITH `tools/build_migrations.py`
--------------------------------------------
`tools/build_migrations.py` reads two documents:

* `tools/catalogue/live_catalogue.json` - the read-only dump of the live
  Supabase project.  It is the source of truth for the migration set.
* `tools/catalogue/mysql_reference.json` - the document this script writes.
  It is the functional specification the live database implements.

The builder cross-checks the two (every table and every column of the MySQL
source has to exist in the live catalogue, otherwise the build fails) and it
names the MySQL module section a migration belongs to in the header of the
file.  `npm run migrate:build` runs

    python tools/translate.py && python tools/build_migrations.py

where the first step refreshes this reference document and the second step
regenerates the 63 generated migrations byte for byte.

Because of that, `tools/translate.py` is a self-contained MySQL -> PostgreSQL
reference translator: it never talks to a database and never writes to one.

A note on the history of this contract: the builder used to read the live
catalogue only, and this document was a by-product nobody consumed.  The
builder now reads both documents and refuses to build when they drift apart,
so the artefact is a hard input of the build again.  This script therefore has
to stay in step with `tools/build_migrations.py`: when the MySQL source or the
translation rules change, `python tools/translate.py` has to run before the
builder, and `--check` is the way to find out whether the document on disk is
still current.

THE TRANSLATION RULES
---------------------
The rules are the ones of `docs/DATABASE_MIGRATION.md`:

==========================  =============================================
MySQL                       PostgreSQL
==========================  =============================================
`ENUM(...)`                 `text` + a named `CHECK (col IN (...))`
`AUTO_INCREMENT`            `GENERATED BY DEFAULT AS IDENTITY`
`TINYINT UNSIGNED`          domain `u8`
`SMALLINT UNSIGNED`         domain `u16`
`MEDIUMINT UNSIGNED`        domain `u24`
`INT UNSIGNED`              domain `u32`
`BIGINT UNSIGNED`           domain `u64`
`YEAR`                      domain `u_year`
`JSON`                      `jsonb`
`VARBINARY`, `BLOB`         `bytea`
`TIMESTAMP`, `DATETIME`     `timestamptz`
`ON UPDATE CURRENT_TIMESTAMP`  a `BEFORE UPDATE` trigger
`INSERT IGNORE`             `INSERT ... ON CONFLICT DO NOTHING`
`REGEXP`                    `~`
`DATEDIFF(a, b)`            `(CAST(a AS date) - CAST(b AS date))`
`TIMESTAMPDIFF(u, a, b)`    `EXTRACT(u FROM age(a, b))`
`IFNULL(a, b)`              `COALESCE(a, b)`
`DATE(a)`                   `CAST(a AS date)`
`a <=> b`                   `a IS NOT DISTINCT FROM b`
`SIGNAL SQLSTATE '45000'`   `RAISE EXCEPTION .. USING ERRCODE '45000'`
==========================  =============================================

Usage:
    python tools/translate.py [--source PATH] [--out PATH] [--check]
"""
