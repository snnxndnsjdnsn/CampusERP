MODULE_HEADER_RE = re.compile(r"^--\s+(\d+[A-Z]?)\.\s+(.+?)\s*$")
SEPARATOR_RE = re.compile(r"^--\s*=+\s*$")


def module_sections(text: str) -> list[dict]:
    """The numbered module sections of the MySQL file.

    A section header is a `-- N. TITLE` comment whose title is written in
    capitals and that sits next to a `-- ===` separator; the numbered notes
    inside section 39 are written in mixed case and are therefore not
    mistaken for a section.
    """
    lines = text.split("\n")
    out: list[dict] = []
    for idx, line in enumerate(lines):
        match = MODULE_HEADER_RE.match(line)
        if not match:
            continue
        title = match.group(2).strip()
        if title != title.upper():
            continue
        previous = lines[idx - 1] if idx > 0 else ""
        following = lines[idx + 1] if idx + 1 < len(lines) else ""
        if not (SEPARATOR_RE.match(previous) or SEPARATOR_RE.match(following)):
            continue
        out.append({
            "number": match.group(1),
            "title": title,
            "line": idx + 1,
        })
    return out


def module_for(line: int, sections: list[dict]) -> dict | None:
    """The module section a statement at `line` belongs to."""
    current = None
    for section in sections:
        if section["line"] <= line:
            current = section
        else:
            break
    return current


